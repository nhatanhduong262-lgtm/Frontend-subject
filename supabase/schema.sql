create table public.users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  password_hash text not null,
  name text not null,
  phone text not null default '',
  role text not null default 'user' check (role in ('user', 'admin')),
  progress_data jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.users enable row level security;

alter table public.users add column if not exists progress_data jsonb not null default '[]'::jsonb;

create index users_email_lower_idx on public.users (lower(email));

create table public.devices (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null,
  manufacturer text not null default '',
  model text not null default '',
  serial_number text not null default '' unique,
  location text not null default '',
  image_url text not null default '',
  status text not null default 'Online' check (status in ('Online', 'Offline')),
  last_seen timestamptz not null default now(),
  specifications jsonb not null default '{}'::jsonb,
  notes text not null default '',
  created_at timestamptz not null default now()
);

alter table public.devices enable row level security;

create index devices_status_idx on public.devices (status);
create index devices_location_idx on public.devices (location);

